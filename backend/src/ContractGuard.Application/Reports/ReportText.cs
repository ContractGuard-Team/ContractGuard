using ContractGuard.Domain.Analysis;
using ContractGuard.Domain.Contracts;
using ContractGuard.Domain.Users;

namespace ContractGuard.Application.Reports;

// Fixed wording of a report in Vietnamese or English (FR-EXP-005). Finding text and quotes are not
// translated: findings are written by the worker in the analysis language, quotes stay verbatim.
public sealed class ReportText
{
    public static readonly ReportText Vi = new(true);
    public static readonly ReportText En = new(false);

    private readonly bool _vi;

    private ReportText(bool vi) => _vi = vi;

    public static ReportText For(UiLanguage language) => language == UiLanguage.En ? En : Vi;

    public string Title => L("Báo cáo thẩm định rủi ro hợp đồng", "Contract risk review report");
    public string GeneratedAt => L("Ngày tạo", "Generated on");
    public string ContractInfo => L("Thông tin hợp đồng", "Contract information");
    public string ContractName => L("Tên hợp đồng", "Contract name");
    public string Version => L("Phiên bản", "Version");
    public string File => L("File", "File");
    public string ApprovalStatus => L("Trạng thái duyệt", "Approval status");
    public string OwnParty => L("Bên mình", "Our party");
    public string Counterparty => L("Đối tác", "Counterparty");
    public string ContractType => L("Loại hợp đồng", "Contract type");
    public string Parties => L("Các bên", "Parties");
    public string ContractValue => L("Giá trị", "Value");
    public string EffectiveDate => L("Ngày hiệu lực", "Effective date");
    public string ExpiryDate => L("Ngày hết hạn", "Expiry date");
    public string GoverningLaw => L("Luật áp dụng", "Governing law");
    public string Unknown => L("Không rõ", "Unknown");
    public string OverallScore => L("Điểm rủi ro tổng", "Overall risk score");
    public string DomainScores => L("Điểm theo nhóm rủi ro", "Scores by risk domain");
    public string Domain => L("Nhóm", "Domain");
    public string Score => L("Điểm", "Score");
    public string Level => L("Mức", "Level");
    public string NotApplicable => L("Không áp dụng", "Not applicable");
    public string ReEnabled => L("Bật lại vì hợp đồng có điều khoản thuộc nhóm này, nên kiểm tra lại ngữ cảnh.", "Turned back on because the contract has clauses of this domain; check the context.");
    public string NoScore => L("Chưa có điểm rủi ro cho lần phân tích này.", "No risk score for this analysis.");
    public string Recommendation => L("Khuyến nghị tổng", "Overall recommendation");
    public string Findings => L("Các rủi ro phát hiện", "Findings");
    public string NoFindings => L("Không có finding nào trong phạm vi báo cáo.", "No findings in the scope of this report.");
    public string ScopeHighOnly => L("Báo cáo chỉ gồm finding mức Cao và Nghiêm trọng.", "This report only lists High and Critical findings.");
    public string Clause => L("Điều khoản", "Clause");
    public string MissingClause => L("Thiếu điều khoản", "Missing clause");
    public string Why => L("Vì sao là rủi ro", "Why it is a risk");
    public string Impact => L("Ảnh hưởng", "Impact");
    public string WhatToDo => L("Hướng xử lý", "Recommendation");
    public string Evidence => L("Trích dẫn", "Quote");
    public string SearchedFor => L("Đã tìm", "Searched for");
    public string References => L("Căn cứ tham khảo", "References");
    public string Handling => L("Trạng thái xử lý", "Handling status");
    public string Checklist => L("Checklist 20 check", "20-check checklist");
    public string Check => L("Check", "Check");
    public string Status => L("Trạng thái", "Status");
    public string Trace => L("Truy vết", "Trace");
    public string Disclaimer => L(
        "Báo cáo do hệ thống AI tạo để hỗ trợ rà soát. Nội dung nêu các rủi ro tiềm ẩn cần xem xét, không phải ý kiến pháp lý và không kết luận điều khoản nào trái pháp luật. Hãy tham khảo luật sư trước khi ra quyết định quan trọng.",
        "This report was generated by an AI system to support review. It lists potential risks to consider; it is not legal advice and does not conclude that any clause is unlawful. Consult a lawyer before important decisions.");

    // FR-RISK-023: the overall recommendation always states how many High and Critical findings there are.
    public string SeveritySummary(int critical, int high) => L(
        $"Có {critical} rủi ro Nghiêm trọng và {high} rủi ro Cao cần xem xét.",
        $"There are {critical} Critical and {high} High risks to review.");

    public string SeverityName(Severity severity) => severity switch
    {
        Severity.Critical => L("Nghiêm trọng", "Critical"),
        Severity.High => L("Cao", "High"),
        Severity.Medium => L("Trung bình", "Medium"),
        _ => L("Thấp", "Low")
    };

    public string LevelName(RiskLevel level) => SeverityName((Severity)(int)level);

    public string DomainName(RiskDomain domain) => domain switch
    {
        RiskDomain.Legal => L("Pháp lý", "Legal"),
        RiskDomain.Financial => L("Tài chính", "Financial"),
        RiskDomain.Operational => L("Vận hành", "Operational"),
        RiskDomain.Compliance => L("Tuân thủ", "Compliance"),
        RiskDomain.Cybersecurity => L("An ninh mạng", "Cybersecurity"),
        RiskDomain.DataPrivacy => L("Dữ liệu và quyền riêng tư", "Data & Privacy"),
        _ => L("Bên thứ ba", "Third-Party")
    };

    public string CheckStatusName(CheckStatus status) => status switch
    {
        CheckStatus.Pass => "PASS",
        CheckStatus.Partial => "PARTIAL",
        CheckStatus.Missing => "MISSING",
        _ => "N/A"
    };

    public string HandlingName(HandlingStatus status) => status switch
    {
        HandlingStatus.RiskAccepted => L("Chấp nhận rủi ro", "Risk accepted"),
        HandlingStatus.NeedsNegotiation => L("Cần đàm phán", "Needs negotiation"),
        HandlingStatus.FalsePositive => L("Không đúng", "False positive"),
        HandlingStatus.Resolved => L("Đã xử lý", "Resolved"),
        _ => L("Chưa xử lý", "Open")
    };

    public string ApprovalName(ApprovalStatus status) => status switch
    {
        global::ContractGuard.Domain.Contracts.ApprovalStatus.New => L("Mới", "New"),
        global::ContractGuard.Domain.Contracts.ApprovalStatus.Analyzing => L("Đang phân tích", "Analyzing"),
        global::ContractGuard.Domain.Contracts.ApprovalStatus.PendingReview => L("Chờ review", "Pending review"),
        global::ContractGuard.Domain.Contracts.ApprovalStatus.Negotiating => L("Đang đàm phán", "Negotiating"),
        global::ContractGuard.Domain.Contracts.ApprovalStatus.Approved => L("Đã duyệt", "Approved"),
        _ => L("Từ chối", "Rejected")
    };

    public string OwnPartyName(global::ContractGuard.Domain.Contracts.OwnParty party) =>
        party == global::ContractGuard.Domain.Contracts.OwnParty.Buyer ? L("Bên mua / khách hàng", "Buyer / customer") : L("Bên bán / nhà cung cấp", "Seller / provider");

    public string ContractTypeName(global::ContractGuard.Domain.Contracts.ContractType type) => type switch
    {
        global::ContractGuard.Domain.Contracts.ContractType.ServiceAgreement => L("Hợp đồng dịch vụ", "Service agreement"),
        global::ContractGuard.Domain.Contracts.ContractType.VendorAgreement => L("Hợp đồng với nhà cung cấp", "Vendor agreement"),
        global::ContractGuard.Domain.Contracts.ContractType.PurchaseAgreement => L("Hợp đồng mua bán", "Purchase agreement"),
        global::ContractGuard.Domain.Contracts.ContractType.Msa => L("Hợp đồng khung (MSA)", "Master services agreement (MSA)"),
        global::ContractGuard.Domain.Contracts.ContractType.Sow => L("Phụ lục công việc (SOW)", "Statement of work (SOW)"),
        _ => L("Khác", "Other")
    };

    // BR-RISK-007, names of the 20 checks.
    public string CheckName(string code) => code switch
    {
        "CY-01" => L("Yêu cầu bảo mật đo lường được", "Measurable security requirements"),
        "CY-02" => L("Mã hóa dữ liệu at-rest và in-transit", "Encryption at rest and in transit"),
        "CY-03" => L("Kiểm soát truy cập, least privilege", "Access control, least privilege"),
        "CY-04" => L("Xác thực đa yếu tố (MFA)", "Multi-factor authentication (MFA)"),
        "CY-05" => L("Ghi log và giám sát an ninh, thời gian lưu log", "Security logging, monitoring and log retention"),
        "CY-06" => L("Quản lý lỗ hổng, SLA vá lỗi", "Vulnerability management, patching SLA"),
        "CY-07" => L("Kiểm thử bảo mật (pentest, đánh giá định kỳ)", "Security testing (pentest, periodic assessment)"),
        "CY-08" => L("Thời hạn thông báo sự cố (24/48/72h)", "Incident notification deadline (24/48/72h)"),
        "CY-09" => L("Quy trình ứng phó và leo thang sự cố", "Incident response and escalation"),
        "CY-10" => L("Sao lưu, khôi phục thảm họa, liên tục kinh doanh (RTO/RPO)", "Backup, disaster recovery, business continuity (RTO/RPO)"),
        "CY-11" => L("Chứng chỉ, chuẩn tuân thủ (ISO 27001, SOC 2)", "Certifications (ISO 27001, SOC 2)"),
        "CY-12" => L("Trách nhiệm khi xảy ra sự cố bảo mật", "Liability for security incidents"),
        "PR-01" => L("Quyền sở hữu dữ liệu thuộc khách hàng", "Customer owns the data"),
        "PR-02" => L("Giới hạn mục đích xử lý dữ liệu", "Purpose limitation"),
        "PR-03" => L("Vị trí lưu trữ, chuyển dữ liệu ra nước ngoài", "Data location, cross-border transfer"),
        "PR-04" => L("Thời hạn lưu trữ dữ liệu", "Data retention period"),
        "PR-05" => L("Xóa hoặc trả dữ liệu và thu hồi truy cập khi chấm dứt", "Return or deletion of data at termination"),
        "TP-01" => L("Kiểm soát nhà thầu phụ", "Subcontractor control"),
        "TP-02" => L("Nghĩa vụ bảo mật áp xuống nhà thầu phụ", "Security flow-down to subcontractors"),
        "TP-03" => L("Quyền kiểm toán bảo mật của khách hàng", "Customer security audit rights"),
        _ => code
    };

    public string Date(DateOnly? date) => date?.ToString(_vi ? "dd/MM/yyyy" : "yyyy-MM-dd", System.Globalization.CultureInfo.InvariantCulture) ?? Unknown;

    public string DateTime(DateTimeOffset value) =>
        value.ToOffset(TimeSpan.FromHours(7)).ToString(_vi ? "dd/MM/yyyy HH:mm" : "yyyy-MM-dd HH:mm", System.Globalization.CultureInfo.InvariantCulture) + " (UTC+7)";

    public string Money(decimal? value, string? currency) =>
        value is null ? Unknown : $"{value.Value.ToString("#,0.##", System.Globalization.CultureInfo.GetCultureInfo(_vi ? "vi-VN" : "en-US"))} {currency}".Trim();

    private string L(string vi, string en) => _vi ? vi : en;
}
